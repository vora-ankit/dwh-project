-- Snowflake setup for the providers and members raw tables.
-- Run in a Snowsight worksheet AFTER `python extract_tables.py` has written files for both
-- tables (INFER_SCHEMA needs files to read). Safe to rerun.
--
-- Replace the two placeholders before running:
--     <your_warehouse>     your X-Small warehouse
--     <storageaccount>     your Azure storage account name

USE ROLE SYSADMIN;
USE WAREHOUSE <your_warehouse>;
USE SCHEMA CLAIMS_DWH.RAW;

-- 1. Stages: same integration as the claims stage, one folder per table
CREATE OR REPLACE STAGE CLAIMS_DWH.RAW.PROVIDERS_EXT_STAGE
  URL = 'azure://<storageaccount>.blob.core.windows.net/raw/providers/'
  STORAGE_INTEGRATION = AZURE_RAW_INT
  FILE_FORMAT = CLAIMS_DWH.RAW.PARQUET_FF;

CREATE OR REPLACE STAGE CLAIMS_DWH.RAW.MEMBERS_EXT_STAGE
  URL = 'azure://<storageaccount>.blob.core.windows.net/raw/members/'
  STORAGE_INTEGRATION = AZURE_RAW_INT
  FILE_FORMAT = CLAIMS_DWH.RAW.PARQUET_FF;

LIST @CLAIMS_DWH.RAW.PROVIDERS_EXT_STAGE;   -- check: Parquet files are listed
LIST @CLAIMS_DWH.RAW.MEMBERS_EXT_STAGE;     -- check: Parquet files are listed

-- 2. Raw tables, columns inferred from the Parquet files
CREATE TABLE IF NOT EXISTS CLAIMS_DWH.RAW.PROVIDERS
  USING TEMPLATE (
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
    FROM TABLE(INFER_SCHEMA(
      LOCATION => '@CLAIMS_DWH.RAW.PROVIDERS_EXT_STAGE',
      FILE_FORMAT => 'CLAIMS_DWH.RAW.PARQUET_FF',
      IGNORE_CASE => TRUE)));

CREATE TABLE IF NOT EXISTS CLAIMS_DWH.RAW.MEMBERS
  USING TEMPLATE (
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
    FROM TABLE(INFER_SCHEMA(
      LOCATION => '@CLAIMS_DWH.RAW.MEMBERS_EXT_STAGE',
      FILE_FORMAT => 'CLAIMS_DWH.RAW.PARQUET_FF',
      IGNORE_CASE => TRUE)));

-- 3. Lineage columns, filled by COPY INTO below
ALTER TABLE CLAIMS_DWH.RAW.PROVIDERS ADD COLUMN IF NOT EXISTS _SOURCE_FILE VARCHAR;
ALTER TABLE CLAIMS_DWH.RAW.PROVIDERS ADD COLUMN IF NOT EXISTS _FILE_ROW NUMBER;
ALTER TABLE CLAIMS_DWH.RAW.PROVIDERS ADD COLUMN IF NOT EXISTS _LOADED_AT TIMESTAMP_LTZ;

ALTER TABLE CLAIMS_DWH.RAW.MEMBERS ADD COLUMN IF NOT EXISTS _SOURCE_FILE VARCHAR;
ALTER TABLE CLAIMS_DWH.RAW.MEMBERS ADD COLUMN IF NOT EXISTS _FILE_ROW NUMBER;
ALTER TABLE CLAIMS_DWH.RAW.MEMBERS ADD COLUMN IF NOT EXISTS _LOADED_AT TIMESTAMP_LTZ;

-- 4. Load
COPY INTO CLAIMS_DWH.RAW.PROVIDERS
  FROM @CLAIMS_DWH.RAW.PROVIDERS_EXT_STAGE
  PATTERN = '.*[.]parquet'
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  INCLUDE_METADATA = (
    _SOURCE_FILE = METADATA$FILENAME,
    _FILE_ROW    = METADATA$FILE_ROW_NUMBER,
    _LOADED_AT   = METADATA$START_SCAN_TIME)
  ON_ERROR = ABORT_STATEMENT;

COPY INTO CLAIMS_DWH.RAW.MEMBERS
  FROM @CLAIMS_DWH.RAW.MEMBERS_EXT_STAGE
  PATTERN = '.*[.]parquet'
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  INCLUDE_METADATA = (
    _SOURCE_FILE = METADATA$FILENAME,
    _FILE_ROW    = METADATA$FILE_ROW_NUMBER,
    _LOADED_AT   = METADATA$START_SCAN_TIME)
  ON_ERROR = ABORT_STATEMENT;

-- 5. Check: expect 2000 providers and 20000 members after the first load
SELECT 'providers' AS table_name, COUNT(*) AS total_rows, COUNT(DISTINCT PROVIDERID) AS distinct_ids
FROM CLAIMS_DWH.RAW.PROVIDERS
UNION ALL
SELECT 'members', COUNT(*), COUNT(DISTINCT MEMBERID)
FROM CLAIMS_DWH.RAW.MEMBERS;
